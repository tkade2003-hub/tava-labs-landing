#!/usr/bin/env python3
"""Build lib/moisturizerImages.ts with data URI WebP images.

Prefers prepped shots in ~/workspace/tava-labs/peptide-moisturizer-assets/
(shot-1-closed.webp etc). If any is missing, converts the four original
supplied photos from the media library instead. Prints the source used
for each shot.
"""
import base64, io, sys
from pathlib import Path
from PIL import Image

HOME = Path.home()
PREPPED_DIR = HOME / "workspace/tava-labs/peptide-moisturizer-assets"
ORIG_DIR = HOME / "workspace/user/media_library/image"
SHOTS = [
    ("shot-1-closed.webp", "ad/ad49a94b5a7b5c29563386c33ba752fc4b08615ebb4735af7187691633406607.jpg", "MOISTURIZER_SHOT_1"),
    ("shot-2-open.webp", "74/74b7665995fc092f50dd3922ec511fb919644a57fcc2559d227f99a8f4c8c725.jpg", "MOISTURIZER_SHOT_2"),
    ("shot-3-trio.webp", "42/4206a4d91a2fac15b3f677299eab8e275619966d9892932705db686c8a123eba.jpg", "MOISTURIZER_SHOT_3"),
    ("shot-4-duo.webp", "84/84b202f4e5b36009d9fb13194a5665a7e65492b9856953a1b5c215e04e4c6a12.jpg", "MOISTURIZER_SHOT_4"),
]
OUT = Path(__file__).resolve().parents[1] / "lib" / "moisturizerImages.ts"

def to_webp_bytes(path: Path) -> bytes:
    im = Image.open(path).convert("RGB")
    if im.width > 1200:
        im = im.resize((1200, round(im.height * 1200 / im.width)), Image.LANCZOS)
    buf = io.BytesIO()
    im.save(buf, "WEBP", quality=82)
    return buf.getvalue()

def main():
    use_prepped = all((PREPPED_DIR / s[0]).exists() for s in SHOTS)
    lines = [
        "/* Peptide Moisturizer product photographs, embedded as data URIs",
        "   because the GitHub connector cannot push binary files. Same",
        "   pattern as lib/heroImages.ts. Generated by",
        "   scripts/build-moisturizer-images.py. */",
        "",
    ]
    names = []
    for prepped_name, orig_rel, const_name in SHOTS:
        if use_prepped:
            src = PREPPED_DIR / prepped_name
            data = to_webp_bytes(src) if src.suffix.lower() != ".webp" else src.read_bytes()
            # normalize: re-encode through PIL to guarantee valid webp data URI
            data = to_webp_bytes(src)
            origin = f"prepped {src}"
        else:
            src = ORIG_DIR / orig_rel
            if not src.exists():
                print(f"MISSING original photo: {src}", file=sys.stderr); sys.exit(1)
            data = to_webp_bytes(src)
            origin = f"original photo {src} converted to WebP at max width 1200"
        print(f"{const_name}: {origin} ({len(data)} bytes)")
        b64 = base64.b64encode(data).decode()
        lines.append(f'export const {const_name} =\n  "data:image/webp;base64,{b64}";\n')
        names.append(const_name)
    lines.append(f"export const MOISTURIZER_IMAGES: string[] = [{', '.join(names)}];\n")
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")

if __name__ == "__main__":
    main()
